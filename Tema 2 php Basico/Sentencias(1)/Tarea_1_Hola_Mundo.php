<?php
    // Vamos a utilizar la función echo.
    /*
     * La función echo permite mostrar uno o varios textos
     * por pantalla.
     * No devuelve ningún valor y puede recibir varios
     * argumentos separados por comas.
     */
    echo "Hola mundo";
    echo "<br>";

    // Vamos a utilizar la función print.
    /*
     * La función print permite mostrar un texto por pantalla.
     * A diferencia de echo, solo acepta un argumento
     * y devuelve siempre el valor 1.
     * Ambas funciones se utilizan para mostrar información,
     * pero echo suele ser más flexible.
     */
    print "Hola mundo";
?>
