<?php
    // Utilizamos la función echo.
    /*
     * echo permite mostrar texto por pantalla.
     * Podemos utilizar comillas simples o dobles.
     * El operador punto (.) sirve para concatenar textos.
     */
    echo 'Hola mundo';
    echo "<br>";
    echo "Hola mundo";
    echo "<br>";
    echo 'Hola ' . 'mundo';
    echo "<br>";

    // Utilizamos la función print.
    /*
     * print también permite mostrar texto por pantalla.
     * Solo acepta un argumento y devuelve el valor 1.
     * Podemos utilizar comillas simples o dobles
     * y concatenar textos mediante el operador punto (.).
     */
    print 'Hola mundo';
    print "<br>";
    print "Hola mundo";
    print "<br>";
    print 'Hola ' . 'mundo';
?>

